export const slugify = (name: string) =>
  name
    .toLowerCase()
    .replace(/'/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

// Every device gets identical seed records (same ids, same timestamps), so syncing
// never duplicates them and never counts as a change.
const SEED_TIME = '2026-01-01T00:00:00.000Z';

export const SEED_EXERCISES: Exercise[] = ROWS.map(([name, primary, secondary, equipment]) => ({
  id: slugify(name),
  name,
  primary,
  secondary,
  equipment,
  isCustom: false,
  createdAt: SEED_TIME,
  updatedAt: SEED_TIME,
}));
